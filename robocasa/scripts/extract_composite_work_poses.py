#!/usr/bin/env python3
"""Extract human-demonstrated manipulation work poses from a LeRobot dataset.

The script is intentionally offline: it reads only the recorded parquet rows and
``extras/episode_*/ep_meta.json``. It never recreates an environment and never
uses fixture poses, so its output describes the robot base positions actually
used in the human demonstrations.

The annotation values in the parquet are integer task IDs. In LeRobot v2.1,
``meta/tasks.jsonl`` is the canonical ``task_index -> task`` table loaded by
``LeRobotDatasetMetadata.load_metadata``. RoboCasa365 stores all human
annotation IDs against that same table, so this script decodes every annotation
field through it rather than interpreting numeric IDs as labels.

``observation.state`` is decoded from ``meta/modality.json``. For PandaOmron
datasets generated by ``robocasa.utils.lerobot_utils.reorder_hdf5_state``:

    state[0:3] = robot0_base_pos = [base_x, base_y, base_z]
    state[3:7] = robot0_base_quat = [x, y, z, w] (xyzw)

The xyzw convention is also used by ``robocasa.work_pose_dataset.current_base_pose``.
"""

