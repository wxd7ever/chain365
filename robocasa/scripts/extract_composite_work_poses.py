@dataclass(frozen=True)
class StateLayout:
    """Slicing metadata for the base position and quaternion in state."""

    base_position_start: int
    base_position_end: int
    base_rotation_start: int
    base_rotation_end: int


@dataclass
class Segment:
    episode_index: int
    segment_index: int
    start_row: int
    end_row: int
    start_frame: int
    end_frame: int
    subtask_idx: int
    annotation_ids: dict[str, int]
    annotation_values: dict[str, str]
    base_x: float
    base_y: float
    base_yaw: float
    annotation_changes_within_segment: bool = False


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Extract manipulation work poses from RoboCasa365 target composite "
            "LeRobot demonstrations."
        )
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        required=True,
        help="LeRobot root containing meta/, data/, and extras/.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="Default: <dataset-root>/work_pose_outputs.",
    )
    parser.add_argument(
        "--debug-episode",
        type=int,
        action="append",
        default=[],
        help="Episode index to print and save a complete decoded segment table. Repeatable.",
    )
    parser.add_argument(
        "--no-plots",
        action="store_true",
        help="Skip scatter plots; CSV extraction and debug tables are still written.",
    )
    parser.add_argument(
        "--max-episodes",
        type=int,
        help="Optional deterministic prefix of episode indices for a quick smoke test.",
    )
    args = parser.parse_args()
    if args.max_episodes is not None and args.max_episodes <= 0:
        parser.error("--max-episodes must be positive")
    if any(index < 0 for index in args.debug_episode):
        parser.error("--debug-episode must be non-negative")
    return args


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"required metadata file is missing: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"invalid JSON in {path}: {exc}") from exc


def _load_tasks(dataset_root: Path) -> dict[int, str]:
    """Load LeRobot's canonical task-index mapping from tasks.jsonl."""

    path = dataset_root / "meta" / "tasks.jsonl"
    if not path.is_file():
        raise FileNotFoundError(f"required LeRobot task table is missing: {path}")
    mapping: dict[int, str] = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
            task_index = int(row["task_index"])
            task = str(row["task"])
        except (KeyError, TypeError, ValueError, json.JSONDecodeError) as exc:
            raise ValueError(f"invalid task record at {path}:{line_number}") from exc
        if task_index in mapping:
            raise ValueError(f"duplicate task_index {task_index} in {path}")
        mapping[task_index] = task
    if not mapping:
        raise ValueError(f"task table is empty: {path}")
    return mapping


def _state_layout_from_modality(modality: Mapping[str, Any]) -> StateLayout:
    state = modality.get("state")
    if not isinstance(state, Mapping):
        raise ValueError("meta/modality.json is missing its state mapping")
    try:
        position = state["base_position"]
        rotation = state["base_rotation"]
        values = (
            int(position["start"]),
            int(position["end"]),
            int(rotation["start"]),
            int(rotation["end"]),
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            "meta/modality.json must define state.base_position and "
            "state.base_rotation start/end indices"
        ) from exc
    result = StateLayout(*values)
    if result.base_position_end - result.base_position_start != 3:
        raise ValueError("base_position must occupy exactly three state dimensions")
    if result.base_rotation_end - result.base_rotation_start != 4:
        raise ValueError("base_rotation must occupy exactly four state dimensions")
    return result


def _scalar(value: Any, *, field: str) -> int:
    array = np.asarray(value)
    if array.size != 1:
        raise ValueError(f"{field} must be scalar or length-one, got shape {array.shape}")
    return int(array.reshape(-1)[0])


def _decode(task_id: int, task_map: Mapping[int, str], *, field: str) -> str:
    try:
        return task_map[task_id]
    except KeyError as exc:
        raise ValueError(
            f"{field} has ID {task_id}, which is absent from meta/tasks.jsonl; "
            "refusing to guess an annotation label"
        ) from exc


def _yaw_xyzw(quaternion: Sequence[float]) -> float:
    """Return planar yaw for RoboCasa's xyzw quaternion convention."""

    quat = np.asarray(quaternion, dtype=np.float64).reshape(-1)
    if quat.size != 4 or not np.isfinite(quat).all():
        raise ValueError("base_rotation must be four finite quaternion values")
    norm = float(np.linalg.norm(quat))
    if norm <= 1e-12:
        raise ValueError("base_rotation quaternion must have non-zero norm")
    x, y, z, w = quat / norm
    return float(math.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z)))


def _base_pose(state: Any, layout: StateLayout) -> tuple[float, float, float]:
    values = np.asarray(state, dtype=np.float64).reshape(-1)
    minimum = max(layout.base_position_end, layout.base_rotation_end)
    if values.size < minimum:
        raise ValueError(
            f"observation.state has {values.size} values, but modality requires {minimum}"
        )
    position = values[layout.base_position_start : layout.base_position_end]
    if not np.isfinite(position).all():
        raise ValueError("base_position contains non-finite values")
    yaw = _yaw_xyzw(values[layout.base_rotation_start : layout.base_rotation_end])
    return float(position[0]), float(position[1]), yaw


def _load_episode_metadata(dataset_root: Path, episode_index: int) -> tuple[int, int]:
    path = dataset_root / "extras" / f"episode_{episode_index:06d}" / "ep_meta.json"
    metadata = _load_json(path)
    if not isinstance(metadata, Mapping):
        raise ValueError(f"episode metadata must be an object: {path}")
    try:
        # These are the actual top-level field names in RoboCasa365 v1.0.
        return int(metadata["layout_id"]), int(metadata["style_id"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            f"{path} must contain top-level integer layout_id and style_id"
        ) from exc


def _is_manipulation(
    stage: str, *, subtask: str, subtask_name: str
) -> tuple[bool, str]:
    """Classify the decoded *stage*, without assuming atomic-task names.

    Current SteamInMicrowave annotations decode to ``pick``, ``place``,
    ``navigate``, ``execute``, and ``done``. In this dataset ``execute`` labels
    the *manipulation* segments for CloseMicrowave and TurnOnMicrowave, not a
    terminal state. The rule therefore excludes navigation and actual completion
    labels only; every other decoded non-empty stage is a manipulation stage.
    This keeps future action labels such as open/close/turn_on/manipulate usable
    without a brittle allowlist.
    """

    normalized = re.sub(r"[_-]+", " ", stage.lower()).strip()
    operation_text = f"{subtask} {subtask_name}".lower()
    if not normalized:
        return False, "empty_stage"
    if re.search(r"\b(navigate|navigation)\b", normalized):
        return False, "navigation_stage"
    if re.search(r"\b(done|complete|completed)\b", normalized):
        return False, "terminal_stage"
    if re.search(r"\b(task complete|all tasks complete)\b", operation_text):
        return False, "terminal_subtask"
    return True, "decoded_non_navigation_non_terminal_stage"


def _read_episode_table(parquet_path: Path) -> dict[str, list[Any]]:
    try:
        import pyarrow.parquet as pq
    except ImportError as exc:
        raise RuntimeError("pyarrow is required to read LeRobot parquet files") from exc
    schema = pq.ParquetFile(parquet_path).schema_arrow
    missing = sorted(set(REQUIRED_COLUMNS).difference(schema.names))
    if missing:
        raise ValueError(f"{parquet_path} is missing required columns: {missing}")
    return pq.read_table(parquet_path, columns=list(REQUIRED_COLUMNS)).to_pydict()


def _segments_from_table(
    table: Mapping[str, Sequence[Any]],
    *,
    task_map: Mapping[int, str],
    state_layout: StateLayout,
) -> list[Segment]:
    row_count = len(table["episode_index"])
    if row_count == 0:
        return []
    if any(len(table[column]) != row_count for column in REQUIRED_COLUMNS):
        raise ValueError("parquet columns have inconsistent row counts")

    segments: list[Segment] = []
    segment_start = 0
    segment_index = 0

    def make_segment(start: int, end: int, index: int) -> Segment:
        episode_index = _scalar(table["episode_index"][start], field="episode_index")
        if any(
            _scalar(table["episode_index"][row], field="episode_index") != episode_index
            for row in range(start + 1, end + 1)
        ):
            raise ValueError("one parquet file unexpectedly contains multiple episode indices")
        annotation_ids = {
            column: _scalar(table[column][start], field=column)
            for column in ANNOTATION_COLUMNS
        }
        annotation_values = {
            column: _decode(value, task_map, field=column)
            for column, value in annotation_ids.items()
        }
        annotation_changes = any(
            _scalar(table[column][row], field=column) != annotation_ids[column]
            for row in range(start + 1, end + 1)
            for column in ANNOTATION_COLUMNS
        )
        base_x, base_y, base_yaw = _base_pose(table["observation.state"][start], state_layout)
        return Segment(
            episode_index=episode_index,
            segment_index=index,
            start_row=start,
            end_row=end,
            start_frame=_scalar(table["frame_index"][start], field="frame_index"),
            end_frame=_scalar(table["frame_index"][end], field="frame_index"),
            subtask_idx=_scalar(table["subtask_idx"][start], field="subtask_idx"),
            annotation_ids=annotation_ids,
            annotation_values=annotation_values,
            base_x=base_x,
            base_y=base_y,
            base_yaw=base_yaw,
            annotation_changes_within_segment=annotation_changes,
        )

    previous_subtask_idx = _scalar(table["subtask_idx"][0], field="subtask_idx")
    for row in range(1, row_count):
        subtask_idx = _scalar(table["subtask_idx"][row], field="subtask_idx")
        if subtask_idx != previous_subtask_idx:
            segments.append(make_segment(segment_start, row - 1, segment_index))
            segment_start = row
            segment_index += 1
            previous_subtask_idx = subtask_idx
    segments.append(make_segment(segment_start, row_count - 1, segment_index))
    return segments


def _segment_row(
    segment: Segment,
    *,
    layout: int,
    style: int,
    previous: Segment | None,
) -> dict[str, Any]:
    values = segment.annotation_values
    stage = values["annotation.human.subtask_stage"]
    is_manipulation, reason = _is_manipulation(
        stage,
        subtask=values["annotation.human.subtask"],
        subtask_name=values["annotation.human.subtask_name"],
    )
    return {
        "episode_index": segment.episode_index,
        "layout": layout,
        "style": style,
        "segment_index": segment.segment_index,
        "start_frame": segment.start_frame,
        "end_frame": segment.end_frame,
        "subtask_idx": segment.subtask_idx,
        "previous_subtask_idx": previous.subtask_idx if previous else None,
        "previous_stage": (
            previous.annotation_values["annotation.human.subtask_stage"]
            if previous
            else None
        ),
        "task_description": values["annotation.human.task_description"],
        "task_name": values["annotation.human.task_name"],
        "subtask": values["annotation.human.subtask"],
        "subtask_name": values["annotation.human.subtask_name"],
        "subtask_stage": stage,
        "base_x": segment.base_x,
        "base_y": segment.base_y,
        "base_yaw": segment.base_yaw,
        "is_manipulation": is_manipulation,
        "classification_reason": reason,
        "annotation_changes_within_segment": segment.annotation_changes_within_segment,
    }


